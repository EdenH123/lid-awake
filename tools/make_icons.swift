// Makes the Lid Awake home-screen icons from assets/app-icon.png (a full-bleed square; iOS rounds
// the corners itself) and writes Icons.swift (PNG data, base64).
// Run: swift tools/make_icons.swift   (from the repo root)
import AppKit

let source = NSImage(contentsOfFile: "assets/app-icon.png")!

func icon(size: Int) -> Data {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: size, pixelsHigh: size, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                               bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSGraphicsContext.current?.imageInterpolation = .high
    source.draw(in: NSRect(x: 0, y: 0, width: size, height: size))
    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])!
}

let small = icon(size: 180), large = icon(size: 512)
try! small.write(to: URL(fileURLWithPath: "tools/icon-180.png"))
try! large.write(to: URL(fileURLWithPath: "tools/icon-512.png"))
let swift = """
// Generated by tools/make_icons.swift from assets/app-icon.png — home-screen icons for the phone page.
import Foundation
let appIcon180 = Data(base64Encoded: "\(small.base64EncodedString())")!
let appIcon512 = Data(base64Encoded: "\(large.base64EncodedString())")!
"""
try! swift.write(toFile: "Icons.swift", atomically: true, encoding: .utf8)
print("icons:", small.count, large.count, "bytes")
