// Draws the Lid Awake home-screen icon and writes Icons.swift (PNG data, base64).
// Run: swift tools/make_icons.swift   (from the repo root)
import AppKit

func icon(size: CGFloat) -> Data {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size), pixelsHigh: Int(size), bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                               bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    let s = size / 100  // design on a 100×100 grid

    // Background: deep graphite, full bleed (iOS rounds the corners itself).
    NSGradient(starting: NSColor(calibratedRed: 0.17, green: 0.17, blue: 0.19, alpha: 1),
               ending: NSColor(calibratedRed: 0.04, green: 0.04, blue: 0.05, alpha: 1))!
        .draw(in: NSRect(x: 0, y: 0, width: size, height: size), angle: -90)

    // Soft green glow behind the screen.
    let glow = NSGradient(colors: [NSColor(calibratedRed: 0.19, green: 0.82, blue: 0.35, alpha: 0.45), .clear])!
    glow.draw(fromCenter: NSPoint(x: 50 * s, y: 55 * s), radius: 0,
              toCenter: NSPoint(x: 50 * s, y: 55 * s), radius: 42 * s, options: [])

    // Lid (bezel) and glowing screen.
    NSColor(calibratedWhite: 0.08, alpha: 1).setFill()
    NSBezierPath(roundedRect: NSRect(x: 19 * s, y: 36 * s, width: 62 * s, height: 41 * s), xRadius: 4 * s, yRadius: 4 * s).fill()
    NSColor(calibratedWhite: 0.42, alpha: 1).setStroke()
    let rim = NSBezierPath(roundedRect: NSRect(x: 19 * s, y: 36 * s, width: 62 * s, height: 41 * s), xRadius: 4 * s, yRadius: 4 * s)
    rim.lineWidth = 0.9 * s; rim.stroke()
    NSGradient(starting: NSColor(calibratedRed: 0.30, green: 0.90, blue: 0.45, alpha: 1),
               ending: NSColor(calibratedRed: 0.13, green: 0.66, blue: 0.29, alpha: 1))!
        .draw(in: NSBezierPath(roundedRect: NSRect(x: 22.5 * s, y: 39.5 * s, width: 55 * s, height: 34 * s), xRadius: 1.6 * s, yRadius: 1.6 * s), angle: -90)
    // Notch.
    NSColor(calibratedWhite: 0.08, alpha: 1).setFill()
    NSBezierPath(roundedRect: NSRect(x: 45 * s, y: 71.5 * s, width: 10 * s, height: 2.5 * s), xRadius: 1.2 * s, yRadius: 1.2 * s).fill()
    // A small "awake" sun on the screen: circle with rays.
    NSColor(calibratedWhite: 1, alpha: 0.95).setFill()
    NSBezierPath(ovalIn: NSRect(x: 45.5 * s, y: 52 * s, width: 9 * s, height: 9 * s)).fill()
    NSColor(calibratedWhite: 1, alpha: 0.95).setStroke()
    for i in 0..<8 {
        let a = Double(i) * .pi / 4
        let ray = NSBezierPath()
        ray.move(to: NSPoint(x: 50 * s + CGFloat(cos(a)) * 7.5 * s, y: 56.5 * s + CGFloat(sin(a)) * 7.5 * s))
        ray.line(to: NSPoint(x: 50 * s + CGFloat(cos(a)) * 10.5 * s, y: 56.5 * s + CGFloat(sin(a)) * 10.5 * s))
        ray.lineWidth = 1.6 * s; ray.lineCapStyle = .round; ray.stroke()
    }

    // Base (aluminium) with thumb groove.
    NSGradient(starting: NSColor(calibratedWhite: 0.86, alpha: 1), ending: NSColor(calibratedWhite: 0.55, alpha: 1))!
        .draw(in: NSBezierPath(roundedRect: NSRect(x: 12 * s, y: 30.5 * s, width: 76 * s, height: 5.5 * s), xRadius: 2.6 * s, yRadius: 2.6 * s), angle: -90)
    NSColor(calibratedWhite: 0.45, alpha: 1).setFill()
    NSBezierPath(roundedRect: NSRect(x: 43 * s, y: 33.8 * s, width: 14 * s, height: 2.2 * s), xRadius: 1.1 * s, yRadius: 1.1 * s).fill()

    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])!
}

let small = icon(size: 180), large = icon(size: 512)
try! small.write(to: URL(fileURLWithPath: "tools/icon-180.png"))
try! large.write(to: URL(fileURLWithPath: "tools/icon-512.png"))
let swift = """
// Generated by tools/make_icons.swift — home-screen icons for the phone page.
import Foundation

let appIcon180 = Data(base64Encoded: "\(small.base64EncodedString())")!
let appIcon512 = Data(base64Encoded: "\(large.base64EncodedString())")!

"""
try! swift.write(toFile: "Icons.swift", atomically: true, encoding: .utf8)
print("icons:", small.count, large.count, "bytes")
